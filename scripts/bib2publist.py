"""Builds `_data/publist.yml` from the CV's BibTeX file.

Bibliographic fields (title, authors, venue, year, doi/url) come from the .bib; site-only fields
(image, description, highlight, link, news1/news2) from `_data/pub_extras.yml`, keyed by the bib key.

    python scripts/bib2publist.py path/to/own-bib.bib

Entries are sorted newest first. Only the keys listed in pub_extras.yml are published (an entry
can be listed with `{}` to publish it without extras); unknown bib keys are reported, not published.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import bibtexparser
import yaml
from bibtexparser.bparser import BibTexParser
from bibtexparser.customization import convert_to_unicode

SITE = Path(__file__).resolve().parent.parent
EXTRAS = SITE / "_data" / "pub_extras.yml"
OUT = SITE / "_data" / "publist.yml"


def _names(author_field: str) -> str:
    names = []
    for name in re.split(r"\s+and\s+", author_field.strip()):
        last, sep, first = name.partition(",")
        names.append(f"{first.strip()} {last.strip()}" if sep else name.strip())
    return ", ".join(names)


def _clean(text: str) -> str:
    return re.sub(r"[{}]", "", text).replace("--", "–").strip()


def _venue(entry: dict) -> str:
    for field in ("venue", "booktitle", "journal", "publisher", "howpublished"):
        if field in entry:
            return _clean(entry[field])
    return ""


def _link(entry: dict) -> dict | None:
    if "eprint" in entry and entry.get("archiveprefix", "").lower() == "arxiv":
        return {"url": f"https://arxiv.org/abs/{entry['eprint']}", "display": "arXiv"}
    if "doi" in entry:
        return {"url": f"https://doi.org/{entry['doi']}", "display": "Paper"}
    if "url" in entry:
        return {"url": entry["url"], "display": "Paper"}
    if "eprint" in entry:
        return {"url": f"https://arxiv.org/abs/{entry['eprint']}", "display": "arXiv"}
    return None


def main(bib_path: str) -> None:
    parser = BibTexParser(common_strings=True)
    parser.customization = convert_to_unicode
    entries = {e["ID"]: e for e in bibtexparser.loads(Path(bib_path).read_text(encoding="utf-8"), parser).entries}
    extras = yaml.safe_load(EXTRAS.read_text(encoding="utf-8")) or {}

    missing = sorted(set(extras) - set(entries))
    if missing:
        sys.exit(f"pub_extras.yml lists keys that are not in the .bib: {missing}")
    for key in sorted(set(entries) - set(extras)):
        print(f"not published (not in pub_extras.yml): {key}")

    publist = []
    for key, extra in extras.items():
        entry, extra = entries[key], dict(extra or {})
        item = {
            "key": key,
            "title": _clean(entry["title"]),
            "authors": _names(_clean(entry.get("author", ""))),
            "venue": extra.pop("venue", None) or _venue(entry),
            "year": int(entry["year"]),
        }
        link = extra.pop("link", None) or _link(entry)
        if link:
            item["link"] = link
        item.update(extra)
        publist.append(item)
    publist.sort(key=lambda p: -p["year"])

    header = "# Generated by scripts/bib2publist.py from the CV's .bib and _data/pub_extras.yml. Do not edit.\n"
    OUT.write_text(header + yaml.safe_dump(publist, allow_unicode=True, sort_keys=False, width=1000), encoding="utf-8")
    print(f"wrote {len(publist)} publications to {OUT.relative_to(SITE)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
